// Deletes the given volume, then renumbers every remaining volume for that
// edition back to a clean 1..N sequence (relabeling any plain "Volume N"
// label to match), mirroring what the UI already does to the local array.
export async function deleteVolumeDb(editionId: string, deletedVolNum: number): Promise<void> {
  const { error: delErr } = await supabase.from('volumes').delete().eq('edition_id', editionId).eq('vol_num', deletedVolNum)
  if (delErr) throw delErr

  const { data, error: fetchErr } = await supabase.from('volumes').select('*').eq('edition_id', editionId).order('vol_num')
  if (fetchErr) throw fetchErr

  for (let i = 0; i < (data ?? []).length; i++) {
    const row = data![i]
    const newVolNum = i + 1
    const newLabel = /^Volume \d+$/.test(row.label) ? `Volume ${newVolNum}` : row.label
    if (row.vol_num !== newVolNum || row.label !== newLabel) {
      const { error } = await supabase.from('volumes').update({ vol_num: newVolNum, label: newLabel }).eq('id', row.id)
      if (error) throw error
    }
  }

  const { error: editionErr } = await supabase.from('editions').update({ volume_count: (data ?? []).length }).eq('id', editionId)
  if (editionErr) throw editionErr
}

// Deducts stock locally (for instant UI feedback) AND persists the same
// change to Supabase in one call — used by Create Invoice / Create Delivery
// Order right after an item is saved.
export async function deductStockAndPersist(pubType: string, periodLabel: string, volumeScope: string, qty: number): Promise<void> {
  const edition = allEditions.find(e => e.pubType === pubType && e.periodLabel === periodLabel)
  if (!edition) return
  const changes = deductStock(pubType, periodLabel, volumeScope, qty)
  for (const c of changes) {
    const { error } = await supabase.from('volumes').update({ stock: c.newStock }).eq('edition_id', edition.id).eq('vol_num', c.volNum)
    if (error) throw error
  }
}

