// Supabase data access layer.
//
// Design: the app keeps its existing pattern of reading data from plain
// in-memory arrays (`customers`, `invoices`, `deliveryOrders`, `allEditions`
// — exported from src/data/*.ts) so every existing read (`.find`, `.filter`,
// `.map`, etc.) across the app keeps working completely unchanged. What
// changes is where those arrays get filled from: `loadAllData()` below
// fetches everything from Supabase once at app startup and populates them.
//
// Every function that used to just mutate one of those arrays directly
// (push/splice/index-assignment) now does two things: persist the change to
// Supabase first (awaited — if it fails, nothing local changes either, so
// the UI never shows something as saved that wasn't), then apply the same
// change to the local array so the UI updates immediately without needing
// a full reload.

