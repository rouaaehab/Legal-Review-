export async function loadAllData(): Promise<void> {
  const [editionsRes, volumesRes, customersRes, subsRes, invoicesRes, invoiceItemsRes, doRes, doItemsRes, fulfillmentsRes] = await Promise.all([
    supabase.from('editions').select('*'),
    supabase.from('volumes').select('*'),
    supabase.from('customers').select('*'),
    supabase.from('customer_subscriptions').select('*'),
    supabase.from('invoices').select('*'),
    supabase.from('invoice_items').select('*').order('sort_order'),
    supabase.from('delivery_orders').select('*'),
    supabase.from('delivery_order_items').select('*').order('sort_order'),
    supabase.from('fulfillments').select('*'),
  ])

  for (const r of [editionsRes, volumesRes, customersRes, subsRes, invoicesRes, invoiceItemsRes, doRes, doItemsRes, fulfillmentsRes]) {
    if (r.error) throw r.error
  }

  // ---- editions + volumes ----
  const volumesByEdition = new Map<string, VolumeRecord[]>()
  for (const v of volumesRes.data ?? []) {
    const list = volumesByEdition.get(v.edition_id) ?? []
    list.push({ volNum: v.vol_num, label: v.label, stock: v.stock })
    volumesByEdition.set(v.edition_id, list)
  }
  const editionsBuilt: Edition[] = (editionsRes.data ?? []).map((e: any) => ({
    id: e.id, pubType: e.pub_type, category: e.category, year: e.year, periodLabel: e.period_label,
    volumeCount: e.volume_count, fullSetPrice: Number(e.full_set_price), pricePerVolume: Number(e.price_per_volume),
    isActive: e.is_active, isAutoGenerated: e.is_auto_generated, notes: e.notes ?? undefined,
    volumes: (volumesByEdition.get(e.id) ?? []).sort((a, b) => a.volNum - b.volNum),
  }))
  allEditions.length = 0
  allEditions.push(...editionsBuilt)

  // ---- customers + subscriptions ----
  const subsByCustomer = new Map<string, CustomerSubscription[]>()
  for (const s of subsRes.data ?? []) {
    const list = subsByCustomer.get(s.customer_id) ?? []
    list.push({ id: s.id, editionId: s.edition_id, volumeScope: s.volume_scope, startDate: s.start_date ?? '' })
    subsByCustomer.set(s.customer_id, list)
  }
  const customersBuilt: Customer[] = (customersRes.data ?? []).map((c: any) => ({
    id: c.id, invoiceNo: c.invoice_no, company: c.company, pic: c.pic ?? '', contact: c.contact ?? '',
    tin: c.tin ?? '', brn: c.brn ?? '', period: c.period ?? '', status: c.status,
    address: c.address ?? '', tel: c.tel ?? '',
    subscriptions: subsByCustomer.get(c.id) ?? [],
  }))
  customers.length = 0
  customers.push(...customersBuilt)

  // ---- invoices + items ----
  const itemsByInvoice = new Map<string, InvoiceItem[]>()
  for (const it of invoiceItemsRes.data ?? []) {
    const list = itemsByInvoice.get(it.invoice_id) ?? []
    list.push({ pub: it.pub, pubCode: it.pub_code ?? undefined, years: it.years, volumes: it.volumes, qty: it.qty, unit: Number(it.unit), total: Number(it.total) })
    itemsByInvoice.set(it.invoice_id, list)
  }
  const invoicesBuilt: Invoice[] = (invoicesRes.data ?? []).map((inv: any) => ({
    id: inv.id, invoiceNo: inv.invoice_no, date: isoToDisplay(inv.date), customer: inv.customer_name,
    customerId: inv.customer_id ?? '', address: inv.address ?? '', attention: inv.attention ?? '',
    items: itemsByInvoice.get(inv.id) ?? [],
    subtotal: Number(inv.subtotal), discount: Number(inv.discount), total: Number(inv.total),
    bank: inv.bank ?? '', account: inv.account ?? '', accountName: inv.account_name ?? '', branch: inv.branch ?? undefined,
    status: inv.status, doId: inv.do_id ?? undefined, preparedBy: inv.prepared_by ?? undefined,
    // New additive columns from migration_2026_08_subscription_backend.sql.
    // Defaults match the SQL DEFAULTs so legacy rows (written before the
    // migration ran) still pass the new CHECK constraints.
    paymentStatus: inv.payment_status ?? 'Unpaid',
    amountPaid: inv.amount_paid != null ? Number(inv.amount_paid) : 0,
    attachment: inv.attachment ?? undefined, attachmentName: inv.attachment_name ?? undefined,
  }))
  invoices.length = 0
  invoices.push(...invoicesBuilt)

  // ---- delivery orders + items ----
  const itemsByDO = new Map<string, DeliveryOrderItem[]>()
  for (const it of doItemsRes.data ?? []) {
    const list = itemsByDO.get(it.delivery_order_id) ?? []
    list.push({ pub: it.pub, pubCode: it.pub_code ?? undefined, years: it.years, volumes: it.volumes, qty: it.qty })
    itemsByDO.set(it.delivery_order_id, list)
  }
  const doBuilt: DeliveryOrder[] = (doRes.data ?? []).map((d: any) => ({
    id: d.id, doNo: d.do_no, trackingNo: d.tracking_no ?? '', date: isoToDisplay(d.date),
    customer: d.customer_name, customerId: d.customer_id ?? '', pic: d.pic ?? '', address: d.address ?? '',
    contact: d.contact ?? '', publication: d.publication ?? '', year: d.year ?? '', volume: d.volume ?? '',
    qty: d.qty, status: d.status,
    items: itemsByDO.get(d.id),
    invoiceId: d.invoice_id ?? undefined, preparedBy: d.prepared_by ?? undefined,
    // Supabase returns the column as `skip_stock_deduction`; default false
    // for any legacy row written before the column existed.
    skipStockDeduction: d.skip_stock_deduction ?? false,
    attachment: d.attachment ?? undefined, attachmentName: d.attachment_name ?? undefined,
  }))
  deliveryOrders.length = 0
  deliveryOrders.push(...doBuilt)

  // ---- fulfillments ----
  const fulfillmentsBuilt: Fulfillment[] = (fulfillmentsRes.data ?? []).map((f: any) => {
    const iso = (f.fulfilled_at ?? '').slice(0, 10)
    return {
      id: f.id, customerId: f.customer_id, editionId: f.edition_id, volNum: f.vol_num,
      fulfillmentDate: isoToDisplay(iso), fulfillmentDateIso: iso,
      unitPrice: Number(f.unit_price),
      invoiceId: f.invoice_id ?? undefined, invoiceItemId: f.invoice_item_id ?? undefined,
      preparedBy: f.prepared_by ?? undefined, notes: f.notes ?? undefined,
    }
  })
  fulfillments.length = 0
  fulfillments.push(...fulfillmentsBuilt)
}

