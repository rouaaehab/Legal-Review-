// Returns the matched user's display name/role on success, or null on any
// failure (unknown email, wrong password, inactive account) — Login.tsx
// shows one generic "invalid credentials" message either way, so it never
// hints at which part was wrong.
export async function verifyLogin(email: string, password: string): Promise<{ name: string; role: 'admin' | 'employee' } | null> {
  const { data, error } = await supabase
    .from('app_users')
    .select('name, role, status, password')
    .eq('email', email)
    .maybeSingle()
  if (error) throw error
  if (!data || data.status !== 'Active' || data.password !== password) return null
  return { name: data.name, role: data.role }
}

// Server-side password change. The SQL function (see
// supabase/migration_2026_08_password.sql) verifies the current password
// and writes the new one in the same transaction — the front-end can't
// do this alone because a direct UPDATE on app_users.password would let
// anyone with the anon key (and a user's email) overwrite any password
// without knowing the current one.
export async function changeAppUserPassword(
  email: string,
  currentPassword: string,
  newPassword: string,
): Promise<void> {
  const { error } = await supabase.rpc('change_app_user_password', {
    p_email: email,
    p_current: currentPassword,
    p_new: newPassword,
  })
  if (error) throw error
}

export async function addAppUserDb(u: { name: string; email: string; role: 'admin' | 'employee' }): Promise<AppUserRow> {
  // New accounts get a placeholder password — there's no "invite by email"
  // flow here (that needs a real backend), so tell whoever's being added
  // this password out of band and have them treat it as temporary.
  const { data, error } = await supabase
    .from('app_users')
    .insert({ name: u.name, email: u.email, role: u.role, password: 'changeme123', status: 'Active' })
    .select()
    .single()
  if (error) throw error
  return { id: data.id, name: data.name, email: data.email, role: data.role, status: data.status, created: isoToDisplay(data.created_at) }
}

